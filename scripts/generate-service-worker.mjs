import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const dist = path.resolve("dist");
const indexPath = path.join(dist, "index.html");
if (!fs.existsSync(indexPath)) {
  console.error("Service worker generation requires dist/index.html.");
  process.exit(1);
}

const html = fs.readFileSync(indexPath, "utf8");
const discovered = Array.from(html.matchAll(/(?:src|href)=["']([^"']+)["']/g), (match) => match[1])
  .filter((url) => url.startsWith("/assets/"));
const core = Array.from(new Set([
  "/",
  "/index.html",
  "/manifest.json",
  "/images/mabis-logo-64.png",
  "/images/mabis-logo-128.webp",
  "/fonts/gnu-freefont/FreeMono-Core.woff2?v=3",
  ...discovered,
]));
const version = crypto.createHash("sha256").update(core.join("\n")).digest("hex").slice(0, 12);

const source = `/* Generated by scripts/generate-service-worker.mjs. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = \`mabis-shell-\${VERSION}\`;
const RUNTIME_CACHE = \`mabis-runtime-\${VERSION}\`;
const CORE = ${JSON.stringify(core, null, 2)};
const CACHE_PREFIXES = ["mabis-shell-", "mabis-runtime-"];

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await Promise.allSettled(CORE.map((url) => cache.add(new Request(url, { cache: "reload" }))));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((name) => CACHE_PREFIXES.some((prefix) => name.startsWith(prefix)))
      .filter((name) => name !== SHELL_CACHE && name !== RUNTIME_CACHE)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

function cacheableResponse(response) {
  return response && response.ok && (response.type === "basic" || response.type === "cors");
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (cacheableResponse(response)) {
    const cache = await caches.open(RUNTIME_CACHE);
    await cache.put(request, response.clone());
  }
  return response;
}

async function staleWhileRevalidate(request) {
  const cached = await caches.match(request);
  const update = fetch(request).then(async (response) => {
    if (cacheableResponse(response)) {
      const cache = await caches.open(RUNTIME_CACHE);
      await cache.put(request, response.clone());
    }
    return response;
  }).catch(() => null);
  return cached || update || Response.error();
}

async function navigation(request) {
  const shell = await caches.open(SHELL_CACHE);
  const network = fetch(request).then(async (response) => {
    if (cacheableResponse(response)) await shell.put("/index.html", response.clone());
    return response;
  });
  const timeout = new Promise((_, reject) => setTimeout(() => reject(new Error("network timeout")), 2600));
  try {
    return await Promise.race([network, timeout]);
  } catch {
    return (await shell.match("/index.html")) || (await shell.match("/")) || network;
  }
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === "/sw.js") return;
  if (/\/(?:api|auth|functions|integrations|entities)(?:\/|$)/i.test(url.pathname)) return;

  if (request.mode === "navigate") {
    event.respondWith(navigation(request));
    return;
  }

  const immutable = url.pathname.startsWith("/assets/")
    || url.pathname.startsWith("/fonts/")
    || url.pathname.startsWith("/images/");
  if (immutable || ["script", "style", "font"].includes(request.destination)) {
    event.respondWith(cacheFirst(request));
    return;
  }
  if (request.destination === "image") {
    event.respondWith(staleWhileRevalidate(request));
  }
});
`;

fs.writeFileSync(path.join(dist, "sw.js"), source);
console.log(`Service worker generated: ${core.length} core resources, version ${version}.`);
