import fs from "node:fs";
import path from "node:path";
import { createServer } from "vite";
import { balancedPalette, spreadBalancedPalette } from "../src/lib/color/themeBalance.js";
import { hexToHsl, readableHex } from "../src/lib/theme-color-utils.js";

const root = process.cwd();
const outputDir = path.join(root, "public/themes");
const defaultCssPath = path.join(root, "src/styles/generated-default-theme.css");
const metaPath = path.join(root, "src/lib/theme-runtime-meta.js");

const server = await createServer({
  configFile: false,
  root,
  resolve: { alias: { "@": path.resolve(root, "src") } },
  server: { middlewareMode: true, hmr: false },
  optimizeDeps: { noDiscovery: true },
  appType: "custom",
  logLevel: "silent",
});

function paletteVars(theme) {
  const list = (theme.swatches || []).filter(Boolean);
  if (list.length === 0) return {};
  const exact = Boolean(theme.pride || theme.exact);
  const semantic = balancedPalette(list);
  const accents = spreadBalancedPalette(list, 8).map((color) => {
    if (!color.startsWith("#")) return color;
    if (!exact) return readableHex(color);
    return parseInt(hexToHsl(color).split(" ")[1]) < 8 ? readableHex(color) : color;
  });
  const vars = {};
  accents.forEach((accent, index) => { vars[`--flag-${index + 1}`] = accent; });
  vars["--palette-count"] = String(list.length);
  vars["--palette-accent-count"] = String(semantic.length);
  const stops = list.map((color, index) => `${color} ${(index / list.length) * 100}% ${((index + 1) / list.length) * 100}%`);
  vars["--palette-stripes"] = `linear-gradient(90deg, ${stops.join(", ")})`;
  vars["--palette-gradient"] = `linear-gradient(90deg, ${list.join(", ")})`;
  return vars;
}

function characterVars(character) {
  if (!character) return {};
  const vars = {};
  for (const key of ["primary", "secondary", "highlight", "shade", "outline", "blue_dark", "special"]) {
    const value = character[`character_${key}`];
    if (value) vars[`--character-${key}`] = value;
  }
  if (character.character_highlight) vars["--glass-edge"] = `${character.character_highlight}59`;
  if (character.character_primary) vars["--rim-light"] = character.character_primary;
  if (character.character_secondary) vars["--glass-tint-2"] = `${character.character_secondary}33`;
  return vars;
}

function cssFor(key, theme, prideTokens) {
  const vars = {
    ...theme.vars,
    ...(theme.pride ? prideTokens(theme, Boolean(theme.dark)) : {}),
    "--ink": theme.dark ? theme.vars["--background"] : theme.vars["--foreground"],
    "--bone": theme.dark ? theme.vars["--foreground"] : theme.vars["--background"],
    "--destructive": theme.vars["--primary"],
    "--destructive-foreground": theme.vars["--primary-foreground"],
    ...paletteVars(theme),
    ...characterVars(theme.character),
  };
  const selector = key === "default"
    ? ":root, html[data-mabis-theme=\"default\"]"
    : `html[data-mabis-theme="${key}"]`;
  const declarations = Object.entries(vars)
    .filter(([, value]) => value !== undefined && value !== null && value !== "")
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `${selector} {\n${declarations}\n}\n`;
}

try {
  const [{ THEMES }, { prideTokens }] = await Promise.all([
    server.ssrLoadModule("/src/lib/theme-catalog.js"),
    server.ssrLoadModule("/src/lib/pride.js"),
  ]);

  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.mkdirSync(outputDir, { recursive: true });
  const meta = {};

  for (const [key, theme] of Object.entries(THEMES)) {
    const css = cssFor(key, theme, prideTokens);
    if (key === "default") fs.writeFileSync(defaultCssPath, css);
    else fs.writeFileSync(path.join(outputDir, `${key}.css`), css);
    meta[key] = {
      bodyClass: theme.bodyClass || `theme-${key}`,
      dark: Boolean(theme.dark),
      pride: Boolean(theme.pride),
    };
  }

  const source = `/* Generated by scripts/generate-theme-assets.mjs. */\nexport const THEME_META = Object.freeze(${JSON.stringify(meta, null, 2)});\nexport const THEME_KEYS = Object.freeze(Object.keys(THEME_META));\nexport const PRIDE_THEME_KEYS = new Set(THEME_KEYS.filter((key) => THEME_META[key].pride));\n`;
  fs.writeFileSync(metaPath, source);
  console.log(`Theme assets generated: ${Object.keys(THEMES).length} themes, ${Object.keys(THEMES).length - 1} on-demand stylesheets.`);
} finally {
  await server.close();
}
