function normalize(value) {
  return String(value || "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[.…]+$/u, (ending) => ending.includes("…") ? "…" : "...")
    .toLowerCase();
}

export function translateUiText(value) {
  const normalized = normalize(value);
  if (!normalized || !/[a-z]/i.test(normalized)) return null;
  if (EXACT_TRANSLATIONS[normalized]) return EXACT_TRANSLATIONS[normalized];

  let match = normalized.match(/^(\d+)\s+(choices|articles|posts|reports|items|members)$/);
  if (match) {
    const noun = { choices: "件の選択肢", articles: "件の記事", posts: "件の投稿", reports: "件の報告", items: "件の項目", members: "人のメンバー" }[match[2]];
    return `${match[1]}${noun}`;
  }

  match = normalized.match(/^show more(?:\s+themes)?\s*\((\d+)\/(\d+)\)$/);
  if (match) return `もっと見る（${match[1]}／${match[2]}）`;

  match = normalized.match(/^show more\s*·\s*(\d+) remaining$/);
  if (match) return `もっと見る・残り${match[1]}件`;

  match = normalized.match(/^advanced font choices\s*·\s*(\d+) total$/);
  if (match) return `上級フォント・全${match[1]}件`;

  match = normalized.match(/^(add|choose|delete|edit|manage|remove|select)\s+(.+)$/);
  if (match) {
    const verb = { add: "追加", choose: "選ぶ", delete: "削除", edit: "編集", manage: "管理", remove: "削除", select: "選ぶ" }[match[1]];
    const noun = NOUNS[match[2]];
    if (noun) return `${noun}を${verb}`;
  }

  match = normalized.match(/^no\s+(.+?)\s+(yet|this week|reported)$/);
  if (match) {
    const noun = NOUNS[match[1]];
    if (noun) return `${match[2] === "this week" ? "今週の" : ""}${noun}はありません`;
  }

  match = normalized.match(/^time keeper\s*\((\d+)\)$/);
  if (match) return `タイムキーパー（${match[1]}）`;

  match = normalized.match(/^week of\s+(.+)$/);
  if (match) return `${match[1]}の週`;

  match = normalized.match(/^(.+)\s+remaining$/);
  if (match && /^\d+$/.test(match[1])) return `残り${match[1]}件`;

  return null;
}

